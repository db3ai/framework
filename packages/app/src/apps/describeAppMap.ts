import { existsSync, readFileSync } from 'node:fs';
import { extname, join, relative, resolve, sep } from 'node:path';
import { appServices, relativeImports } from './checkAppBoundaries';
import { discoverApps } from './discoverApps';
import type { AppBoundaryProblem } from './checkAppBoundaries';

/** One call an app's contract promises. */
export interface AppMapCall {
	name: string;
	/** Parameter names, in order. */
	parameters: string[];
	/** The first sentence of the call's documentation comment, or an empty string. */
	summary: string;
}

/** A service inside an app: a lower-level piece with its own contract. */
export interface AppMapService {
	id: string;
	/** Its contract file, relative to the project, or null when it is missing. */
	contract: string | null;
	contractName: string | null;
	calls: AppMapCall[];
	/** Other services of the same app whose contracts its code imports. */
	uses: string[];
}

/** One app on the map: what it is, what it needs and what it promises. */
export interface AppMapEntry {
	id: string;
	name: string;
	description: string;
	apiVersion: number;
	requires: string[];
	optional: string[];
	/** Apps that name this one in requires or optional. */
	usedBy: string[];
	/** The contract file, relative to the project, or null when the app has none. */
	contract: string | null;
	/** The name of the contract's default-exported interface, or null. */
	contractName: string | null;
	calls: AppMapCall[];
	/** The services inside the app, from its `services/` folder. */
	services: AppMapService[];
}

/**
 * Reads a project's apps into a map of services, their dependencies and each contract's calls.
 *
 * Reads manifests and contract files as text; never loads app code. A contract's calls are the
 * members of its default-exported interface. A service uses another when its code imports that
 * service's contract.
 * @param directory - Project root holding `apps/`.
 * @returns One entry per app, ordered by identifier.
 */
export function describeAppMap(directory: string): AppMapEntry[] {
	const root = resolve(directory);
	const apps = discoverApps(root);
	return apps.map(app => {
		const manifest = app.manifest;
		const text = app.contract && existsSync(app.contract) ? readFileSync(app.contract, 'utf8') : null;
		const contract = text === null ? null : readContract(text);
		const show = (file: string) => relative(root, file).split(sep).join('/');
		const found = app.packageName ? [] : appServices(app.directory);
		const services = found.map(service => {
			const file = join(service.directory, 'contract.ts');
			const read = existsSync(file) ? readContract(readFileSync(file, 'utf8')) : null;
			const imports = relativeImports(service.directory).map(item => item.target.slice(0, item.target.length - extname(item.target).length));
			const uses = found.filter(other => other !== service && imports.includes(join(other.directory, 'contract'))).map(other => other.id);
			return { id: service.id, contract: existsSync(file) ? show(file) : null, contractName: read?.name ?? null, calls: read?.calls ?? [], uses };
		});
		return {
			id: manifest.id, name: manifest.name, description: manifest.description ?? '', apiVersion: manifest.apiVersion ?? 1,
			requires: Object.keys(manifest.requires ?? {}).sort(), optional: Object.keys(manifest.optional ?? {}).sort(),
			usedBy: apps.filter(other => ({ ...other.manifest.requires, ...other.manifest.optional })[manifest.id] !== undefined).map(other => other.manifest.id).sort(),
			contract: app.contract ? relative(root, app.contract).split(sep).join('/') : null,
			contractName: contract?.name ?? null, calls: contract?.calls ?? [], services,
		};
	}).sort((a, b) => a.id.localeCompare(b.id));
}

/**
 * Formats the map as Markdown: a Mermaid diagram of the apps and their dependencies, then each
 * app's contract as a table of calls. The output depends only on the source, so a saved copy can be
 * compared with a fresh one. Imports that cross a boundary are drawn on the diagram and listed, so
 * the map shows where the code does not yet conform.
 * @param map - Result of describeAppMap.
 * @param problems - Boundary problems from checkAppBoundaries, when they should show on the map.
 */
export function formatAppMap(map: readonly AppMapEntry[], problems: readonly AppBoundaryProblem[] = []): string {
	const lines = ['# App map', '', '<!-- Generated by `db3 apps:map`. Do not edit: change a manifest or a contract, then run it again. -->', ''];
	lines.push('Each box is an app: one folder under `apps/`. A rounded box inside it is a service: a lower-level piece of that app, in its `services/` folder. An arrow points from an app or service to one it uses, and it may import only that one\'s contract. `db3 apps:check` enforces this.', '');
	lines.push('```mermaid', 'flowchart LR');
	const calls = (count: number) => `${count} call${count === 1 ? '' : 's'}`;
	for (const app of map) {
		const title = `${label(app.name)}<br/>${app.contract ? `contract v${app.apiVersion} · ${calls(app.calls.length)}` : 'no contract'}`;
		if (!app.services.length) { lines.push(`\t${app.id}["${title}"]`); continue; }
		lines.push(`\tsubgraph ${app.id}["${title}"]`);
		for (const service of app.services) lines.push(`\t\t${app.id}__${service.id}(["${label(service.id)}<br/>${service.contract ? calls(service.calls.length) : 'no contract'}"])`);
		for (const service of app.services) for (const other of service.uses) lines.push(`\t\t${app.id}__${service.id} --> ${app.id}__${other}`);
		lines.push('\tend');
	}
	for (const app of map) {
		for (const dependency of app.requires) lines.push(`\t${app.id} -->|requires| ${dependency}`);
		for (const dependency of app.optional) lines.push(`\t${app.id} -.->|optional| ${dependency}`);
	}
	const crossings = [...new Set(problems.filter(problem => problem.target && problem.target !== problem.app).map(problem => `${problem.app} ${problem.target}`))].sort();
	for (const crossing of crossings) lines.push(`\t${crossing.split(' ')[0]} -.->|crosses the boundary| ${crossing.split(' ')[1]}`);
	lines.push('```', '', '## Conformance', '');
	if (!problems.length) lines.push(`All ${map.length} apps${map.some(app => app.services.length) ? ' and their services' : ''} keep to each other's contracts.`, '');
	else {
		lines.push(`${problems.length} place${problems.length === 1 ? '' : 's'} in the code do${problems.length === 1 ? 'es' : ''} not conform yet:`, '');
		for (const problem of problems) lines.push(`- \`${problem.file}\` (${problem.app}): ${problem.message}`);
		lines.push('');
	}
	for (const app of map) {
		lines.push(`## ${app.name} (\`${app.id}\`)`, '');
		if (app.description) lines.push(app.description, '');
		lines.push(`- Uses: ${[...app.requires.map(id => `\`${id}\``), ...app.optional.map(id => `\`${id}\` (optional)`)].join(', ') || 'no other app'}`);
		lines.push(`- Used by: ${app.usedBy.map(id => `\`${id}\``).join(', ') || 'no other app'}`);
		if (!app.contract) lines.push('- Contract: none, so no other app may import from it.', '');
		else {
			lines.push(`- Contract: \`${app.contract}\`${app.contractName ? `, interface \`${app.contractName}\`` : ''}, API generation ${app.apiVersion}`, '');
			lines.push(...callTable(app.calls));
		}
		for (const service of app.services) {
			lines.push(`### ${service.id} (service in \`${app.id}\`)`, '');
			lines.push(`- Uses: ${service.uses.map(id => `\`${id}\``).join(', ') || 'no other service'}`);
			lines.push(`- Used by: ${app.services.filter(other => other.uses.includes(service.id)).map(other => `\`${other.id}\``).join(', ') || 'no other service'}`);
			if (!service.contract) { lines.push('- Contract: missing. Give it a `contract.ts`.', ''); continue; }
			lines.push(`- Contract: \`${service.contract}\`${service.contractName ? `, interface \`${service.contractName}\`` : ''}`, '');
			lines.push(...callTable(service.calls));
		}
	}
	return `${lines.join('\n').trimEnd()}\n`;
}

/** A contract's calls as a Markdown table, or a line saying it has none. */
function callTable(calls: readonly AppMapCall[]): string[] {
	if (!calls.length) return ['The contract promises no calls yet.', ''];
	return ['| Call | What it does |', '| --- | --- |', ...calls.map(call => `| \`${call.name}(${call.parameters.join(', ')})\` | ${call.summary.replaceAll('|', '\\|')} |`), ''];
}

/** Text safe inside a Mermaid node label. */
function label(text: string) {
	return text.replace(/["\[\]<>]/g, ' ').trim();
}

/** Reads the default-exported interface of a contract file: its name and its method members. */
function readContract(text: string): { name: string; calls: AppMapCall[] } | null {
	const head = /export\s+default\s+interface\s+([A-Za-z_$][\w$]*)[^{]*\{/.exec(text);
	if (!head) return null;
	const start = head.index + head[0].length;
	const calls: AppMapCall[] = [];
	let depth = 0;
	let comment = '';
	let member = '';
	for (let index = start; index < text.length; index++) {
		const char = text[index]!;
		if (depth === 0 && !member.trim() && text.startsWith('/**', index)) {
			const end = text.indexOf('*/', index);
			if (end < 0) break;
			comment = text.slice(index + 3, end);
			index = end + 1;
			continue;
		}
		if (text.startsWith('//', index)) { index = text.indexOf('\n', index); if (index < 0) break; continue; }
		if (char === '}' && depth === 0) break;
		if ('({[<'.includes(char)) depth++;
		// `=>` closes nothing.
		else if (')}]'.includes(char) || (char === '>' && text[index - 1] !== '=')) depth--;
		if (depth === 0 && (char === ';' || (char === '\n' && member.trim() && !/[,:|&(]\s*$/.test(member)))) {
			const call = readMember(member, comment);
			if (call) calls.push(call);
			member = ''; comment = '';
			continue;
		}
		member += char;
	}
	return { name: head[1]!, calls };
}

/** Reads one interface member; only methods are calls. */
function readMember(member: string, comment: string): AppMapCall | null {
	const match = /^\s*([A-Za-z_$][\w$]*)\s*(?:<[^(]*>)?\s*\(/.exec(member);
	if (!match) return null;
	const open = match[0].length;
	let depth = 1;
	let end = open;
	for (; end < member.length && depth > 0; end++) {
		if ('({[<'.includes(member[end]!)) depth++;
		else if (')}]'.includes(member[end]!) || (member[end] === '>' && member[end - 1] !== '=')) depth--;
	}
	const parameters: string[] = [];
	let part = '';
	depth = 0;
	let previous = '';
	for (const char of `${member.slice(open, end - 1)},`) {
		if ('({[<'.includes(char)) depth++;
		else if (')}]'.includes(char) || (char === '>' && previous !== '=')) depth--;
		previous = char;
		if (char === ',' && depth === 0) { const name = /^\s*(\.\.\.)?([A-Za-z_$][\w$]*)/.exec(part); if (name) parameters.push(`${name[1] ?? ''}${name[2]}`); part = ''; }
		else part += char;
	}
	const prose = comment.split('\n').map(line => line.replace(/^\s*\*?\s?/, '')).join(' ').split(/\s@\w+/)[0]!.replace(/\s+/g, ' ').trim();
	const sentence = /^(.*?[.!?])(\s|$)/.exec(prose);
	return { name: match[1]!, parameters, summary: sentence ? sentence[1]! : prose };
}
